import { toCsv } from "./report-catalogue";

export type Snapshot = {
  ref: string;
  reportId: string;
  title: string;
  ownerName: string;
  generatedAt: Date;
  freshness: Date;
  contents: string;
  summary: string[];
  unit: string;
  basis: string;
  columns: { key: string; label: string; kind: string }[];
  rows: Record<string, string | number | null>[];
  metrics: { label: string; value: string; unit: string }[];
};

export const brisbane = (d: Date) =>
  new Intl.DateTimeFormat("en-AU", {
    timeZone: "Australia/Brisbane",
    dateStyle: "medium",
    timeStyle: "short",
  }).format(d) + " AEST";
const esc = (s: unknown) =>
  String(s ?? "").replace(
    /[&<>"]/g,
    (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c] as string,
  );

/** Section 7: every file carries the report ID, title, author, time, filters, unit, basis and freshness. */
export function metaRows(e: Snapshot, viewer: string): [string, string][] {
  return [
    ["Report", `${e.reportId === "BUILDER" ? "Custom" : e.reportId} ${e.title}`],
    ["Export", e.ref],
    ["Generated by", e.ownerName],
    ["Generated at", brisbane(e.generatedAt)],
    ["Data as of", brisbane(e.freshness)],
    ["Opened by", viewer],
    ["Contents", e.contents],
    ["Unit", e.unit || "As labelled"],
    ["Date basis", e.basis || "As labelled"],
    ["Filters", e.summary.join(" · ")],
    [
      "Note",
      "Snapshot: later changes to records are not reflected. Mock export from the Medisense prototype.",
    ],
  ];
}

export function exportFile(e: Snapshot, format: string, viewer: string) {
  const meta = metaRows(e, viewer);
  const base = `${e.ref}-${e.reportId}`.toLowerCase();
  const metricRows = e.metrics.map((m) => ({ label: m.label, value: m.value, unit: m.unit }));
  if (format === "CSV") {
    const body =
      toCsv(e.columns, e.rows, meta) +
      (metricRows.length
        ? `\r\n\r\n${toCsv(
            [
              { key: "label", label: "Measure" },
              { key: "value", label: "Value" },
              { key: "unit", label: "Unit" },
            ],
            metricRows,
            [],
          )}`
        : "");
    return { body, type: "text/csv; charset=utf-8", name: `${base}.csv`, inline: false };
  }
  if (format === "XLSX") {
    const cell = (v: unknown) =>
      `<Cell><Data ss:Type="${typeof v === "number" ? "Number" : "String"}">${esc(v ?? "")}</Data></Cell>`;
    const sheet = (name: string, rows: unknown[][]) =>
      `<Worksheet ss:Name="${esc(name)}"><Table>${rows.map((r) => `<Row>${r.map(cell).join("")}</Row>`).join("")}</Table></Worksheet>`;
    const body = `<?xml version="1.0"?><?mso-application progid="Excel.Sheet"?><Workbook xmlns="urn:schemas-microsoft-com:office:spreadsheet" xmlns:ss="urn:schemas-microsoft-com:office:spreadsheet">${sheet("About", meta)}${metricRows.length ? sheet("Summary", [["Measure", "Value", "Unit"], ...metricRows.map((m) => [m.label, m.value, m.unit])]) : ""}${e.columns.length ? sheet("Rows", [e.columns.map((c) => c.label), ...e.rows.map((r) => e.columns.map((c) => r[c.key]))]) : ""}</Workbook>`;
    return { body, type: "application/vnd.ms-excel", name: `${base}.xls`, inline: false };
  }
  throw new Error(`${format} files are made by the PDF renderer, not here.`);
}
